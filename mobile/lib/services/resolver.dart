/// On-device, ad-free playback core (§12, re-architected: no server).
///
/// The phone talks to YouTube directly (youtube_explode_dart), picks streams,
/// caches the result for up to 6h in SQLite, and the player combines separate
/// video + audio streams on the device. No IFrame, no embedded YouTube player,
/// no ads, no tracking.
///
/// Only videos already in the on-device library (i.e. that passed scoped
/// ingestion) can be resolved.
library;

import 'dart:async';
import 'dart:convert';
import 'dart:io' show SocketException;

import 'package:youtube_explode_dart/youtube_explode_dart.dart' as yte;

import '../data/app_database.dart';
import '../models/resolved_video.dart';

const resolveTimeout = Duration(seconds: 20);
const resolveCacheTtl = Duration(hours: 6);
const resolveRetryAfterSec = 30;
const _urlExpiryMargin = Duration(minutes: 10);

/// Resolution failed; try again after [retryAfterSec] (§12 failure contract).
class ResolveFailed implements Exception {
  ResolveFailed(this.reason, {this.retryAfterSec = resolveRetryAfterSec, this.offline = false});
  final String reason;
  final int retryAfterSec;

  /// No network: videos can't play, but feeds, search and material still work.
  final bool offline;
  @override
  String toString() => 'ResolveFailed($reason; retry in ${retryAfterSec}s)';
}

// --- extractor abstraction (lets tests run without network) ------------------

enum RawKind { muxed, videoOnly, audioOnly }

class RawStream {
  RawStream({
    required this.kind,
    required this.url,
    this.width = 0,
    this.height = 0,
    required this.codec,
    required this.container,
    required this.bitrate,
  });

  final RawKind kind;
  final Uri url;
  final int width;
  final int height;
  final String codec; // e.g. 'avc1.640028', 'vp9', 'mp4a.40.2', 'opus'
  final String container; // 'mp4', 'webm'
  final int bitrate; // bits/s
}

class RawCaption {
  RawCaption({required this.url, required this.languageCode, required this.isAuto});
  final Uri url;
  final String languageCode;
  final bool isAuto;
}

class RawExtraction {
  RawExtraction({
    required this.title,
    required this.description,
    required this.duration,
    required this.thumbnail,
    required this.streams,
    required this.captions,
  });

  final String title;
  final String description;
  final Duration? duration;
  final String? thumbnail;
  final List<RawStream> streams;
  final List<RawCaption> captions;
}

abstract class StreamExtractor {
  Future<RawExtraction> extract(String youtubeId);
}

/// Talks to YouTube directly from the phone.
class YoutubeExplodeExtractor implements StreamExtractor {
  YoutubeExplodeExtractor([yte.YoutubeExplode? yt]) : _yt = yt ?? yte.YoutubeExplode();
  final yte.YoutubeExplode _yt;

  @override
  Future<RawExtraction> extract(String youtubeId) async {
    // Only the streams are waited for: title, description and thumbnail are
    // already in the library, and captions get 2 s at most (the video can start
    // without them).
    final results = await Future.wait([
      _manifest(youtubeId),
      _yt.videos.closedCaptions
          .getManifest(youtubeId, formats: const [yte.ClosedCaptionFormat.vtt])
          .then<Object?>((m) => m)
          .timeout(const Duration(seconds: 2), onTimeout: () => null)
          .catchError((Object _) => null), // captions are optional
    ]);
    final manifest = results[0] as yte.StreamManifest;
    final cc = results[1] as yte.ClosedCaptionManifest?;

    RawStream videoStream(yte.VideoStreamInfo s, RawKind kind) => RawStream(
          kind: kind,
          url: s.url,
          width: s.videoResolution.width,
          height: s.videoResolution.height,
          codec: s.videoCodec,
          container: s.container.name,
          bitrate: s.bitrate.bitsPerSecond,
        );

    return RawExtraction(
      title: '',
      description: '',
      duration: null,
      thumbnail: null,
      streams: [
        for (final s in manifest.muxed) videoStream(s, RawKind.muxed),
        for (final s in manifest.videoOnly) videoStream(s, RawKind.videoOnly),
        for (final s in manifest.audioOnly)
          RawStream(
            kind: RawKind.audioOnly,
            url: s.url,
            codec: s.audioCodec,
            container: s.container.name,
            bitrate: s.bitrate.bitsPerSecond,
          ),
      ],
      captions: [
        for (final t in cc?.tracks ?? const <yte.ClosedCaptionTrackInfo>[])
          RawCaption(url: t.url, languageCode: t.language.code, isAuto: t.isAutoGenerated),
      ],
    );
  }

  /// Streams without downloading YouTube's watch page first (much faster);
  /// falls back to the full way if YouTube refuses that.
  Future<yte.StreamManifest> _manifest(String youtubeId) async {
    try {
      return await _yt.videos.streams
          .getManifest(youtubeId, requireWatchPage: false)
          .timeout(const Duration(seconds: 8));
    } catch (_) {
      return _yt.videos.streams.getManifest(youtubeId);
    }
  }

  void close() => _yt.close();
}

// --- pure selection logic ----------------------------------------------------

bool _isH264(String codec) => codec.startsWith('avc1');

/// Builds playback options, best first.
///
/// For each resolution we prefer H.264 (hardware-decoded on every Android
/// device) over VP9/AV1, and pair video-only streams with the best AAC audio
/// (falling back to any audio). The 360p muxed stream is always kept as a
/// reliable single-URL fallback.
List<PlaybackOption> buildOptions(List<RawStream> streams) {
  final audio = streams.where((s) => s.kind == RawKind.audioOnly).toList()
    ..sort((a, b) {
      final aac = (b.codec.startsWith('mp4a') ? 1 : 0) - (a.codec.startsWith('mp4a') ? 1 : 0);
      return aac != 0 ? aac : b.bitrate.compareTo(a.bitrate);
    });
  final bestAudio = audio.isEmpty ? null : audio.first;

  final byHeight = <int, PlaybackOption>{};
  int rank(RawStream s) => (_isH264(s.codec) ? 2 : 0) + (s.container == 'mp4' ? 1 : 0);

  if (bestAudio != null) {
    final videos = streams.where((s) => s.kind == RawKind.videoOnly && s.height > 0).toList()
      ..sort((a, b) {
        final r = rank(b).compareTo(rank(a));
        return r != 0 ? r : b.bitrate.compareTo(a.bitrate);
      });
    for (final v in videos) {
      byHeight.putIfAbsent(
        v.height,
        () => PlaybackOption(
            quality: '${v.height}p', height: v.height, videoUrl: '${v.url}', audioUrl: '${bestAudio.url}'),
      );
    }
  }

  final muxed = streams.where((s) => s.kind == RawKind.muxed).toList()..sort((a, b) => b.height.compareTo(a.height));
  for (final m in muxed) {
    // Muxed wins at its own height: one URL is the most robust thing to play.
    byHeight[m.height] = PlaybackOption(quality: '${m.height}p', height: m.height, videoUrl: '${m.url}');
  }

  return byHeight.values.toList()..sort((a, b) => b.height.compareTo(a.height));
}

/// English caption tracks only: one manual (if any) then one auto-generated.
List<CaptionTrack> englishCaptions(List<RawCaption> captions) {
  bool isEn(RawCaption c) => c.languageCode.toLowerCase().split(RegExp('[-_]')).first == 'en';
  final manual = captions.where((c) => isEn(c) && !c.isAuto);
  final auto = captions.where((c) => isEn(c) && c.isAuto);
  return [
    if (manual.isNotEmpty) CaptionTrack(url: '${manual.first.url}', isAuto: false),
    if (auto.isNotEmpty) CaptionTrack(url: '${auto.first.url}', isAuto: true),
  ];
}

DateTime? urlExpiry(Uri url) {
  final exp = int.tryParse(url.queryParameters['expire'] ?? '');
  return exp == null ? null : DateTime.fromMillisecondsSinceEpoch(exp * 1000, isUtc: true);
}

ResolvedVideo buildResolved(String videoId, RawExtraction raw, {required DateTime now}) {
  final options = buildOptions(raw.streams);
  if (options.isEmpty) throw ResolveFailed('no playable streams');

  final best = raw.streams.where((s) => s.kind != RawKind.audioOnly && s.height > 0).toList()
    ..sort((a, b) => b.height.compareTo(a.height));
  final isVertical = best.isNotEmpty && best.first.height > best.first.width;

  var expiresAt = now.add(resolveCacheTtl);
  for (final o in options) {
    for (final u in [o.videoUrl, o.audioUrl]) {
      final e = u == null ? null : urlExpiry(Uri.parse(u));
      if (e != null && e.subtract(_urlExpiryMargin).isBefore(expiresAt)) {
        expiresAt = e.subtract(_urlExpiryMargin);
      }
    }
  }

  return ResolvedVideo(
    videoId: videoId,
    title: raw.title,
    description: raw.description,
    durationSec: raw.duration?.inSeconds,
    isVertical: isVertical,
    thumbnail: raw.thumbnail,
    options: options,
    captions: englishCaptions(raw.captions),
    expiresAt: expiresAt,
  );
}

// --- resolver with cache -----------------------------------------------------

class Resolver {
  Resolver(this._db, this._extractor, {DateTime Function()? clock})
      : _clock = clock ?? (() => DateTime.now().toUtc());

  final AppDatabase _db;
  final StreamExtractor _extractor;
  final DateTime Function() _clock;

  /// Drops the cached streams (e.g. YouTube expired a URL mid-playback).
  void invalidate(String videoId) => _db.execute('DELETE FROM video_resolutions WHERE video_id = ?', [videoId]);

  Future<ResolvedVideo> resolve(String videoId) async {
    final now = _clock();
    final cached = _db.select(
      'SELECT payload FROM video_resolutions WHERE video_id = ? AND expires_at > ?',
      [videoId, now.millisecondsSinceEpoch],
    );
    if (cached.isNotEmpty) {
      return ResolvedVideo.fromJson(jsonDecode(cached.first['payload'] as String) as Map<String, dynamic>);
    }

    final rows = _db.select(
        "SELECT source, source_id, title, description, duration_sec, thumbnail_url FROM videos WHERE id = ? AND status = 'active'",
        [videoId]);
    if (rows.isEmpty) throw ResolveFailed('not in library'); // not a general YouTube player
    if (rows.first['source'] != 'youtube') throw ResolveFailed('unsupported source');

    final RawExtraction raw;
    try {
      raw = await _extractor.extract(rows.first['source_id'] as String).timeout(resolveTimeout);
    } on TimeoutException {
      throw ResolveFailed('timed out after ${resolveTimeout.inSeconds}s');
    } on ResolveFailed {
      rethrow;
    } on SocketException catch (e) {
      throw ResolveFailed('$e', offline: true);
    } catch (e) {
      final msg = '$e';
      throw ResolveFailed(msg, offline: msg.contains('Failed host lookup') || msg.contains('SocketException'));
    }

    // What the library already knows needn't be fetched again.
    final lib = rows.first;
    final filled = RawExtraction(
      title: raw.title.isNotEmpty ? raw.title : lib['title'] as String? ?? '',
      description: raw.description.isNotEmpty ? raw.description : lib['description'] as String? ?? '',
      duration: raw.duration ??
          (lib['duration_sec'] == null ? null : Duration(seconds: lib['duration_sec'] as int)),
      thumbnail: raw.thumbnail ?? lib['thumbnail_url'] as String?,
      streams: raw.streams,
      captions: raw.captions,
    );
    final resolved = buildResolved(videoId, filled, now: now);
    _db.execute(
      'INSERT OR REPLACE INTO video_resolutions (video_id, payload, resolved_at, expires_at) VALUES (?, ?, ?, ?)',
      [videoId, jsonEncode(resolved.toJson()), now.millisecondsSinceEpoch, resolved.expiresAt.millisecondsSinceEpoch],
    );
    return resolved;
  }
}
